"""Rebuild src/input/pad_icons.bin from the Kenney "Input Prompts" pack (CC0).

The repository already contains the generated atlas; this script is only
needed to change the icons. Download the pack from https://kenney.nl/assets/input-prompts
(version 1.5), extract it and run:

    python tools/make_pad_atlas.py <extracted Kenney folder>

Requires Pillow (pip install pillow).
"""
import hashlib, sys
from pathlib import Path
from PIL import Image, ImageFilter

if len(sys.argv) != 2:
    raise SystemExit(__doc__)
KENNEY = Path(sys.argv[1])
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "input"
PS = KENNEY / "PlayStation Series" / "Double"
XB = KENNEY / "Xbox Series" / "Double"

ICONS = [
    # PlayStation, shared by DualSense and DualShock
    ("ps_l1", PS / "playstation_trigger_l1.png"), ("ps_r1", PS / "playstation_trigger_r1.png"),
    ("ps_l2", PS / "playstation_trigger_l2.png"), ("ps_r2", PS / "playstation_trigger_r2.png"),
    ("ps_l3", PS / "playstation_button_l3.png"), ("ps_r3", PS / "playstation_button_r3.png"),
    ("ps_ls_up", PS / "playstation_stick_l_up.png"), ("ps_ls_down", PS / "playstation_stick_l_down.png"),
    ("ps_ls_left", PS / "playstation_stick_l_left.png"), ("ps_ls_right", PS / "playstation_stick_l_right.png"),
    ("ps_rs_up", PS / "playstation_stick_r_up.png"), ("ps_rs_down", PS / "playstation_stick_r_down.png"),
    ("ps_rs_left", PS / "playstation_stick_r_left.png"), ("ps_rs_right", PS / "playstation_stick_r_right.png"),
    ("ps_dpad_up", PS / "playstation_dpad_up.png"), ("ps_dpad_down", PS / "playstation_dpad_down.png"),
    ("ps_dpad_left", PS / "playstation_dpad_left.png"), ("ps_dpad_right", PS / "playstation_dpad_right.png"),
    # DualSense: white symbols, Create / Options / touch pad
    ("ds_cross", PS / "playstation_button_cross.png"), ("ds_circle", PS / "playstation_button_circle.png"),
    ("ds_square", PS / "playstation_button_square.png"), ("ds_triangle", PS / "playstation_button_triangle.png"),
    ("ds_create", PS / "playstation5_button_create.png"), ("ds_options", PS / "playstation5_button_options.png"),
    ("ds_touchpad", PS / "playstation5_touchpad_press.png"),
    # DualShock 3/4: classic colour symbols, Share / Options / touch pad
    ("d4_cross", PS / "playstation_button_color_cross.png"), ("d4_circle", PS / "playstation_button_color_circle.png"),
    ("d4_square", PS / "playstation_button_color_square.png"),
    ("d4_triangle", PS / "playstation_button_color_triangle.png"),
    ("d4_share", PS / "playstation4_button_share.png"), ("d4_options", PS / "playstation4_button_options.png"),
    ("d4_touchpad", PS / "playstation4_touchpad_press.png"),
    # Xbox One / Series (any other controller)
    ("xb_a", XB / "xbox_button_color_a.png"), ("xb_b", XB / "xbox_button_color_b.png"),
    ("xb_x", XB / "xbox_button_color_x.png"), ("xb_y", XB / "xbox_button_color_y.png"),
    ("xb_lb", XB / "xbox_lb.png"), ("xb_rb", XB / "xbox_rb.png"),
    ("xb_lt", XB / "xbox_lt.png"), ("xb_rt", XB / "xbox_rt.png"),
    ("xb_ls", XB / "xbox_ls.png"), ("xb_rs", XB / "xbox_rs.png"),
    ("xb_view", XB / "xbox_button_view.png"), ("xb_menu", XB / "xbox_button_menu.png"),
    ("xb_ls_up", XB / "xbox_stick_l_up.png"), ("xb_ls_down", XB / "xbox_stick_l_down.png"),
    ("xb_ls_left", XB / "xbox_stick_l_left.png"), ("xb_ls_right", XB / "xbox_stick_l_right.png"),
    ("xb_rs_up", XB / "xbox_stick_r_up.png"), ("xb_rs_down", XB / "xbox_stick_r_down.png"),
    ("xb_rs_left", XB / "xbox_stick_r_left.png"), ("xb_rs_right", XB / "xbox_stick_r_right.png"),
    ("xb_dpad_up", XB / "xbox_dpad_up.png"), ("xb_dpad_down", XB / "xbox_dpad_down.png"),
    ("xb_dpad_left", XB / "xbox_dpad_left.png"), ("xb_dpad_right", XB / "xbox_dpad_right.png"),
]

CELL, COLUMNS = 64, 8
atlas = Image.new("RGBA", (CELL * COLUMNS, CELL * 8), (0, 0, 0, 0))
for index, (name, path) in enumerate(ICONS):
    icon = Image.open(path).convert("RGBA").crop((12, 12, 116, 116)).resize((56, 56), Image.LANCZOS)
    cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    alpha = icon.getchannel("A").filter(ImageFilter.MaxFilter(5))   # dark outline for light backgrounds
    outline = Image.new("RGBA", icon.size, (16, 16, 20, 255))
    outline.putalpha(alpha.point(lambda a: a * 3 // 4))
    cell.alpha_composite(outline, (4, 4))
    cell.alpha_composite(icon, (4, 4))
    atlas.alpha_composite(cell, ((index % COLUMNS) * CELL, (index // COLUMNS) * CELL))

r, g, b, a = atlas.split()
raw = Image.merge("RGBA", (b, g, r, a)).tobytes()  # D3DFMT_A8R8G8B8 memory order
(OUT / "pad_icons.bin").write_bytes(raw)
lines = ["#pragma once", "// Generated by tools/make_pad_atlas.py from Kenney Input Prompts 1.5 (CC0).",
         "namespace pad_icons {",
         f"constexpr unsigned cell = {CELL}, columns = {COLUMNS}, width = {CELL * COLUMNS}, height = {CELL * 8};",
         "enum Icon : int {"]
lines += [f"    {name} = {index}," for index, (name, _) in enumerate(ICONS)]
lines += ["    none = -1", "};", "}  // namespace pad_icons", ""]
(OUT / "pad_icons.hpp").write_text("\n".join(lines), encoding="utf-8")
print(len(ICONS), "icons", hashlib.sha256(raw).hexdigest())
